CREATE TABLE IF NOT EXISTS asset_rules (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NOT NULL,
    asset_type ENUM('stock','crypto','gold') NOT NULL,
    asset_symbol VARCHAR(20) NOT NULL,
    rule_type ENUM('price_level','pct_change_24h','trailing_stop','week52_break') NOT NULL,
    direction ENUM('above','below') NULL,
    intent ENUM('buy_target','take_profit','stop_loss') NULL,
    level_usd DECIMAL(20,8) NULL,
    pct DECIMAL(5,2) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    params_version INT UNSIGNED NOT NULL DEFAULT 0,
    baseline_pending BOOLEAN NOT NULL DEFAULT FALSE,
    last_beyond BOOLEAN NULL,
    peak_price_usd DECIMAL(20,8) NULL,
    week52_ref_usd DECIMAL(20,8) NULL,
    last_alerted_at TIMESTAMP NULL,
    last_alerted_price_usd DECIMAL(20,8) NULL,
    cooldown_until TIMESTAMP NULL,
    triggered_at TIMESTAMP NULL,
    triggered_price_usd DECIMAL(20,8) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_asset_rules_symbol_active (asset_symbol, is_active),
    KEY idx_asset_rules_user (user_id),
    CONSTRAINT fk_asset_rules_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
